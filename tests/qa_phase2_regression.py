"""Phase 2 UI smoke: locally assembled original HTML/CSS/JS in Chromium.

Browser policy prohibits navigation to localhost. This validates behavior/visuals, not true ESM network fetching.
"""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json, shutil, tempfile
root=Path(__file__).resolve().parents[1]
html=(root/'index.html').read_text(encoding='utf-8')
css=(root/'assets/css/styles.css').read_text(encoding='utf-8')+'\n'+(root/'assets/css/phase2.css').read_text(encoding='utf-8')+'\n'+(root/'assets/css/viewer.css').read_text(encoding='utf-8')
data=(root/'assets/js/data.js').read_text(encoding='utf-8').replace('export const ','const ')
js=(root/'assets/js/app.js').read_text(encoding='utf-8')
js=js.replace("import {SOURCES,SECTIONS,EVIDENCE,TIMELINE,STATUS} from './data.js';",'').replace("import {viewerHTML,mountViewer} from './viewer.js';",'const {viewerHTML,mountViewer}=window.__viewerExports;')
iiif=(root/'assets/js/iiif.js').read_text(encoding='utf-8').replace('export const ','const ').replace('export function ','function ').replace('export async function ','async function ')
annotations=(root/'assets/js/annotations.js').read_text(encoding='utf-8').replace('export const ','const ').replace('export function ','function ')
viewer=(root/'assets/js/viewer.js').read_text(encoding='utf-8').replace("import {MANIFESTS, YALE_CATALOG, parseManifest, fetchManifest, pageUrl} from './iiif.js';",'').replace("import {ANNOTATIONS_KEY,MAX_ANNOTATIONS,parseAnnotations,parseAnnotationsBackup,backupAnnotations,folioAnnotations,mergeAnnotations,coordinateInImage} from './annotations.js';",'').replace('export function ','function ')
html=html.replace('<link rel="stylesheet" href="assets/css/styles.css">','<style>'+css+'</style>')
html=html.replace('<link rel="stylesheet" href="assets/css/phase2.css">','').replace('<link rel="stylesheet" href="assets/css/viewer.css">','')
html=html.replace('<script type="module" src="assets/js/app.js"></script>','')
# Provide isolated, working localStorage in about:blank context
store='''<script>Object.defineProperty(window,'localStorage',{configurable:true,value:(()=>{const m=new Map();return {getItem(k){return m.has(k)?m.get(k):null},setItem(k,v){m.set(k,String(v))},removeItem(k){m.delete(k)},clear(){m.clear()}}})()});</script>'''
html=html.replace('</body>',store+'<script>'+data+'\n'+iiif+'\n'+'(function(){'+annotations+'\n'+viewer+'\nwindow.__viewerExports={viewerHTML,mountViewer};})();'+'\n'+js+'</script></body>')
checks=[];errors=[]
def check(label,condition):
    if not condition:raise AssertionError(label)
    checks.append('PASS  '+label)
def click(page,locator):page.locator(locator).click()
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=shutil.which('chromium') or '/usr/bin/chromium',args=['--no-sandbox'])
    desktop=browser.new_page(viewport={'width':1440,'height':960},accept_downloads=True)
    desktop.on('pageerror',lambda e:errors.append('JS: '+str(e)))
    desktop.on('console',lambda m:errors.append('console: '+m.text) if m.type=='error' else None)
    desktop.set_content(html,wait_until='load')
    desktop.wait_for_selector('.feature')
    check('Carga la portada',desktop.locator('h1').first.inner_text().startswith('El libro'))
    check('Aparecen tres accesos de expedición',desktop.locator('.feature').count()==3)
    check('Están los botones de búsqueda y preferencias',desktop.locator('#openSearch').count()==1 and desktop.locator('#openPreferences').count()==1)
    desktop.screenshot(path=str(root/'tests/regresion-fase2-escritorio.png'),full_page=True,animations='disabled')
    click(desktop,'#openSearch')
    check('Buscador global abre con clic',desktop.locator('#searchDialog').evaluate('(d)=>d.open'))
    desktop.locator('#globalSearch').fill('botánica')
    check('Búsqueda con acentos',desktop.locator('.command-option').count()>0)
    desktop.locator('#globalSearch').fill('sinresultadoabsurdo')
    check('Sin resultados muestra mensaje',desktop.locator('.command-results .empty').count()==1)
    desktop.locator('#globalSearch').fill('cronolog')
    desktop.locator('#globalSearch').press('Enter')
    check('Enter del buscador navega',desktop.locator('.moment').count()==5 and not desktop.locator('#searchDialog').evaluate('(d)=>d.open'))
    # Opening a source detail directly from search must not leave focus on a hidden dialog
    click(desktop,'#openSearch')
    desktop.locator('#globalSearch').fill('botánica')
    desktop.locator('#globalSearch').press('Enter')
    check('Búsqueda abre ficha contextual',desktop.locator('#detailDialog').evaluate('(d)=>d.open'))
    click(desktop,'#closeDialog')
    check('Cerrar ficha desde búsqueda devuelve el foco al archivo',not desktop.locator('#detailDialog').evaluate('(d)=>d.open') and not desktop.locator('#searchDialog').evaluate('(d)=>d.open'))
    desktop.keyboard.press('Control+k')
    check('Atajo Ctrl+K abre búsqueda',desktop.locator('#searchDialog').evaluate('(d)=>d.open'))
    desktop.keyboard.press('Escape')
    check('Escape cierra búsqueda',not desktop.locator('#searchDialog').evaluate('(d)=>d.open'))
    click(desktop,'#openPreferences')
    check('Preferencias abren por botón',desktop.locator('#preferencesDialog').evaluate('(d)=>d.open'))
    click(desktop,'[data-skin=pergamino]')
    check('Cambiar skin desde galería',desktop.locator('body').get_attribute('data-theme')=='pergamino')
    check('Skin tiene aria-pressed',desktop.locator('[data-skin=pergamino]').get_attribute('aria-pressed')=='true')
    click(desktop,'[data-size=amplia]')
    check('Tamaño amplio de letra',desktop.locator('body').get_attribute('data-type')=='amplia')
    click(desktop,'#motionToggle')
    check('Desactivar animaciones',desktop.locator('body').get_attribute('data-motion')=='off')
    check('Preferencias persistidas',json.loads(desktop.evaluate("localStorage.getItem('voynich404-type')"))=='amplia')
    click(desktop,'#resetPreferences')
    check('Restablecer preferencias',desktop.locator('body').get_attribute('data-theme')=='nocturno' and desktop.locator('body').get_attribute('data-type')=='normal' and desktop.locator('body').get_attribute('data-motion')=='on')
    click(desktop,'[data-close-dialog=preferencesDialog]')
    check('Cerrar preferencias',not desktop.locator('#preferencesDialog').evaluate('(d)=>d.open'))
    click(desktop,'[data-view=codice]')
    check('Todas las secciones preservadas',desktop.locator('.section-card').count()==6)
    click(desktop,'[data-section=astro]')
    check('Detalle de secciones',desktop.locator('#detailDialog').evaluate('(d)=>d.open'))
    click(desktop,'#closeDialog')
    click(desktop,'[data-view=evidencias]')
    check('Se preservan nueve evidencias',desktop.locator('.research-card').count()==9)
    click(desktop,'[data-filter=hipotesis]')
    check('Filtrado dinámico accesible',desktop.locator('.research-card').count()==1 and desktop.locator('[data-filter=hipotesis]').get_attribute('aria-pressed')=='true')
    click(desktop,'[data-evidence]')
    check('Modal de evidencia conserva fuentes',desktop.locator('#detailDialog .dialog-sources a').count()>0)
    click(desktop,'#closeDialog')
    click(desktop,'[data-view=cuaderno]')
    desktop.locator('#noteTitle').fill('<img src=x onerror=alert(1)>')
    desktop.locator('#noteBody').fill('Test del diario <script>alert(1)</script>')
    click(desktop,'#noteForm button[type=submit]')
    check('Guardar anotación',desktop.locator('.note').count()==1)
    check('No ejecuta HTML guardado',desktop.locator('.note img').count()==0)
    with desktop.expect_download() as event:
        click(desktop,'#exportNotes')
    download=event.value
    with tempfile.NamedTemporaryFile(suffix='.json') as f:
        download.save_as(f.name)
        note_data=json.loads(Path(f.name).read_text())
    check('Exportar diario con datos',note_data['notes'][0]['title'].startswith('<img'))
    click(desktop,'[data-delete]')
    check('Eliminar nota',desktop.locator('.note').count()==0)
    click(desktop,'[data-view=fuentes]')
    check('Las cinco fuentes siguen disponibles',desktop.locator('.source-row').count()==5)
    click(desktop,'#themeCycle')
    check('Selector secundario de skin',desktop.locator('body').get_attribute('data-theme')=='pergamino')
    # Mobile at 390, then 320 px, verify backdrop/menu and keyboard
    mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.on('pageerror',lambda e:errors.append('mobile JS: '+str(e)))
    mobile.set_content(html,wait_until='load')
    mobile.screenshot(path=str(root/'tests/regresion-fase2-movil.png'),full_page=True,animations='disabled')
    check('Sin desbordamiento móvil 390',mobile.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    click(mobile,'#mobileMenu')
    check('Menú móvil abre y anuncia estado',mobile.locator('.sidebar').get_attribute('class').endswith('open') and mobile.locator('#mobileMenu').get_attribute('aria-expanded')=='true')
    check('Menú móvil tiene fondo bloqueante',mobile.locator('#sidebarBackdrop').evaluate('(e)=>e.classList.contains("shown")'))
    click(mobile,'[data-view=codice]')
    check('Navegación móvil cierra menú',mobile.locator('.section-card').count()==6 and mobile.locator('#mobileMenu').get_attribute('aria-expanded')=='false')
    click(mobile,'#mobileMenu')
    click(mobile,'#sidebarBackdrop')
    check('Fondo cierra menú móvil',not mobile.locator('.sidebar').evaluate('(e)=>e.classList.contains("open")'))
    click(mobile,'#openSearch')
    check('Búsqueda operativa en móvil',mobile.locator('#globalSearch').is_visible())
    mobile.locator('#globalSearch').fill('plantas')
    check('Resultados legibles en móvil',mobile.locator('.command-option').count()>0)
    click(mobile,'[data-close-dialog=searchDialog]')
    mobile.set_viewport_size({'width':320,'height':700})
    check('Sin desbordamiento móvil 320',mobile.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
    check('Sin errores JavaScript',len(errors)==0)
    browser.close()
report='# VOYNICH 404 · Informe de QA fase 2\n\n'+'\n'.join('- '+line for line in checks)+f'\n\n**Total:** {len(checks)} comprobaciones superadas.\n\n**Errores de página o consola:** {errors if errors else "ninguno"}.\n\n**Alcance:** Chromium sin navegación HTTP (bloqueada administrativamente). Se ejecutaron el HTML y CSS reales y los cuerpos de los módulos JS concatenados para pruebas, con localStorage simulado. El servidor de archivos y la sintaxis ESM se verifican por separado. Este test no prueba la carga ESM HTTP ni los lanzadores en Windows o Linux.\n'
(root/'tests/REGRESION_FASE2.md').write_text(report,encoding='utf8')
print('\n'.join(checks));print('TOTAL',len(checks))
