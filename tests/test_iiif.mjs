import {readFileSync} from 'node:fs';
import {strict as assert} from 'node:assert';
import {parseManifest,pageUrl,yaleUrl,MANIFESTS} from '../assets/js/iiif.js';
const dir=new URL('./fixtures/',import.meta.url);
const v2=JSON.parse(readFileSync(new URL('iiif-v2.json',dir),'utf8'));
const v3=JSON.parse(readFileSync(new URL('iiif-v3.json',dir),'utf8'));
const a=parseManifest(v2,{requireVoynich:true});
const b=parseManifest(v3,{requireVoynich:true});
assert.equal(a.length,3);
assert.equal(a[0].label,'f1r');
assert.equal(a[2].index,2);
assert.equal(b.length,1);
assert.equal(b[0].label,'fol. 16r');
assert.match(pageUrl(a[0],1400),/full\/1400,\/0\/default\.jpg/);
assert.match(pageUrl(b[0],1400),/full\/1400,\/0\/default\.jpg/);
assert.equal(yaleUrl('javascript:alert(1)'),null);
assert.equal(yaleUrl('https://yale.edu.evil.example/foo'),null);
assert.equal(yaleUrl('http://collections.library.yale.edu/foo'),null);
assert.equal(MANIFESTS.length,2);
assert.throws(()=>parseManifest({},{}),/IIIF/);
assert.throws(()=>parseManifest({...v2,'@id':'https://example.org/other'}, {requireVoynich:true}),/Voynich/);
assert.throws(()=>parseManifest({sequences:[{canvases:[{label:'x',images:[{resource:{'@id':'https://evil.org/image.jpg'}}]}]}]},{}),/imágenes/);
assert.throws(()=>parseManifest({items:Array.from({length:601},()=>({type:'Canvas'}))}),/límites/);
console.log('PASS 14 IIIF unit assertions (v2/v3, image URL, Yale hosts, invalid data, limits)');
