import assert from 'node:assert/strict';
import {ATLAS_ENTRIES,ATLAS_CATEGORIES,cleanAtlasFavorites,filterAtlas,normalizedFolio,findAtlasFolio} from '../assets/js/atlas-data.js';
let count=0;const ok=(name,fn)=>{fn();count++;console.log('PASS',name)};
ok('sixteen entries',()=>assert.equal(ATLAS_ENTRIES.length,16));
ok('unique ids',()=>assert.equal(new Set(ATLAS_ENTRIES.map(x=>x.id)).size,16));
ok('folio and source on all records',()=>assert.ok(ATLAS_ENTRIES.every(x=>/^f\d+[rv]\d?$/.test(x.folio)&&x.observed&&x.interpretation&&x.source)));
ok('source-backed categories',()=>assert.ok(ATLAS_ENTRIES.every(x=>Object.hasOwn(ATLAS_CATEGORIES,x.category))));
ok('no species claims encoded',()=>assert.ok(ATLAS_ENTRIES.every(x=>!x.species)));
ok('botanical filter',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{category:'botanica'}).length,8));
ok('astronomical filter',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{category:'astronomia'}).length,3));
ok('zodiac filter',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{category:'zodiaco'}).length,3));
ok('cosmology filter',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{category:'cosmologia'}).length,2));
ok('diacritics search',()=>assert.ok(filterAtlas(ATLAS_ENTRIES,{term:'pleyades'}).length>=1));
ok('folio search',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{term:'f68r3'}).length,1));
ok('no matches',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{term:'no-existe-esta-ficha'}).length,0));
ok('favorites filter',()=>assert.equal(filterAtlas(ATLAS_ENTRIES,{favoritesOnly:true,favorites:['herb-f2v']}).length,1));
ok('deduplicate favorites',()=>assert.deepEqual(cleanAtlasFavorites(['herb-f2v','herb-f2v','unknown']),['herb-f2v']));
ok('invalid favorite storage',()=>assert.deepEqual(cleanAtlasFavorites({x:1}),[]));
ok('canonical folio',()=>assert.equal(normalizedFolio('f68r3'),'f68r3'));
ok('folio label recto',()=>assert.equal(normalizedFolio('Folio 68 recto 3'),'f68r3'));
ok('folio label verso',()=>assert.equal(normalizedFolio('Folio 2 verso'),'f2v'));
ok('matching exact',()=>assert.equal(findAtlasFolio([{label:'f2v'},{label:'f2v1'}],'f2v1'),1));
ok('missing folio does not map to another',()=>assert.equal(findAtlasFolio([{label:'f2v'}],'f71r'),-1));
console.log(`PASS ${count} atlas assertions`);
